from __future__ import annotations

"""高考作文 60 分制 · 分项分等 · ABCDE 五档评分标准。

权威分级标准的唯一来源：作文批改 chain 把 RUBRIC 注入评分 prompt，
程序用 level_of() 由总分确定性推档次，确保总分/档次/分项严格一致、可审计。
"""

LEVELS = ["A", "B", "C", "D", "E"]

_LEVEL_NAMES = {"A": "一等", "B": "二等", "C": "三等", "D": "四等", "E": "五等"}

RUBRIC = """高考作文 60 分制评分标准（分项分等）：

【基础等级 40 分】

一、内容 20 分（按给分区间五档）：
- 一等(20-17)：切合题意，中心突出，内容充实，思想健康，感情真挚
- 二等(16-12)：符合题意，中心明确，内容较充实，思想健康，感情真实
- 三等(11-7)：基本符合题意，中心基本明确，内容单薄，思想基本健康，感情基本真实
- 四等(6-4)：偏离题意，中心不明确，内容不当，思想不够健康，感情不够真实
- 五等(3-0)：严重偏离题意，无中心，内容贫乏，思想不健康，感情虚假

二、表达 20 分（按给分区间五档）：
- 一等(20-17)：符合文体要求，结构严谨，语言流畅，字迹工整
- 二等(16-12)：符合文体要求，结构完整，语言通顺，字迹清楚
- 三等(11-7)：基本符合文体要求，结构基本完整，语言基本通顺，字迹基本清楚
- 四等(6-4)：不符合文体要求，结构混乱，语言不通顺、语病多，字迹潦草难辨
- 五等(3-0)：无文体特征，结构混乱，语言严重不通，字迹难辨

【发展等级 20 分】
- 一等(20-17)：深刻（透过现象看本质、揭示事物内在因果、观点有启发性）；丰富（材料丰富、论据充实、形象丰满、意境深远）；有文采（用词贴切、句式灵活、善用修辞、文句有表现力）；有创意（见解新颖、构思新巧、推理想象有独到之处、有个性特征）
- 二等(16-12)：较深刻、较丰富、较有文采、较有创意
- 三等(11-7)：略显深刻、略显丰富、略显文采、略显创意
- 四等(6-4)：个别语句有深意、个别内容较好、个别语句较精彩、个别地方有新意
- 五等(3-0)：无明显深刻、丰富、文采、创意

【说明】
1. 发展等级四项（深刻、丰富、有文采、有创意）不求全，只要一点突出即可按较高档给分。
2. 三个分项（内容/表达/发展）各为 0-20 整数分；总分 = 内容 + 表达 + 发展（0-60 分）。
3. 总分对应档次：A 一等 54-60；B 二等 48-53；C 三等 42-47；D 四等 36-41；E 五等 0-35。
"""


def level_of(total: int) -> str:
    """由总分确定性推档次（A-E），不信任 LLM 自行映射。"""
    if total >= 54:
        return "A"
    if total >= 48:
        return "B"
    if total >= 42:
        return "C"
    if total >= 36:
        return "D"
    return "E"


def level_name(level: str) -> str:
    return _LEVEL_NAMES.get(level, "")
