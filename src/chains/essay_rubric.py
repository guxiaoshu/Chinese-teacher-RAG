from __future__ import annotations

"""高考作文 60 分制 · ABCDE 五档评分标准（整体总分分档）。

权威分级标准的唯一来源：作文批改 chain 把 RUBRIC 注入评分 prompt，
程序用 level_of() 由总分确定性推档次，确保总分/档次严格一致、可审计。
"""

LEVELS = ["A", "B", "C", "D", "E"]

_LEVEL_NAMES = {"A": "一等", "B": "二等", "C": "三等", "D": "四等", "E": "五等"}

RUBRIC = """高考作文 60 分制 · 五档评分标准：

【A 档（一等，50–60 分）】
切合题意、立意准，中心突出；内容充实，论据扎实；文体规范，结构严谨；语言流畅有质感，字迹工整。发展等级能占到深刻、丰富、文采、创意里至少一项突出。
考场高分范文水平。

【B 档（二等，42–49 分）】
符合题意，中心明确；内容比较充实，有论据；文体对，结构完整；语言通顺，少量小语病，字迹清楚。有一点亮点，但不够出彩，四平八稳。
绝大多数正常写完、不跑题的中上作文都落在这一档，也是考生冲的主力区间。

【C 档（三等，30–41 分）】
基本符合题意，立意沾边但不够精准；中心基本明确，内容单薄，例子老套或者论证很浅；文体大体对，结构基本完整；语言基本通顺，语病不算少。
没跑题，但写得平淡、空洞，是大部分普通学生的常态。

【D 档（四等下，18–29 分）】
偏离题意，抓不住材料核心；中心模糊，内容空洞；结构松散，语病多；文体混乱。
属于明显写偏，或者字数严重不足（400–600 字）。

【E 档（17 分及以下）】
严重跑题、完全脱离材料；抄袭、套作；字数极少（200 字以内）；思想不当；字迹潦草几乎无法辨认。
全抄阅读材料一般 10 分以内；
只写几句话、几十字，几分。

【评分说明】
1. 总分 0–60 分，档次由程序根据总分自动计算。
2. 总分对应档次：A 50–60；B 42–49；C 30–41；D 18–29；E 0–17。
"""


def level_of(total: int) -> str:
    """由总分确定性推档次（A-E），不信任 LLM 自行映射。"""
    if total >= 50:
        return "A"
    if total >= 42:
        return "B"
    if total >= 30:
        return "C"
    if total >= 18:
        return "D"
    return "E"


def level_name(level: str) -> str:
    return _LEVEL_NAMES.get(level, "")
